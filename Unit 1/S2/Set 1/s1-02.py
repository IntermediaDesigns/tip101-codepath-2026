#  *                    Problem 2: Print Doubled List Items
#
#    Write a function doubled() that takes in a list of integers lst as a parameter
#    and prints each item in the list multiplied by two.


def doubled(lst):
    for items in lst:
        print(items * 2)


lst = [1, 2, 3]
doubled(lst)

# Example Output:
# 2
# 4
# 6
